# Title: Lucky Numbers Finder

# Discovers "lucky numbers" - integers that survive a sieving process similar to the
# Sieve of Eratosthenes but removing every nth number based on position. It's fascinating
# because lucky numbers share mysterious properties with primes but are generated differently!

def sieve_lucky(limit):
    """Generate lucky numbers up to limit using the lucky number sieve."""
    numbers = list(range(1, limit + 1))
    step = 2
    
    while step <= len(numbers):
        # Remove every step-th number (1-indexed)
        numbers = [numbers[i] for i in range(len(numbers)) if (i + 1) % step != 0]
        step += 1
    
    return numbers

def is_twin_lucky(lucky_set, n):
    """Check if n and n+2 are both lucky."""
    return n in lucky_set and n + 2 in lucky_set

def analyze_lucky(limit=1000):
    """Analyze and display lucky number properties."""
    lucky = sieve_lucky(limit)
    lucky_set = set(lucky)
    
    print("╔════════════════════════════════════════════╗")
    print("║      Lucky Numbers Investigation           ║")
    print("╚════════════════════════════════════════════╝\n")
    
    print(f"First 20 lucky numbers:")
    print(lucky[:20])
    print(f"\nTotal lucky numbers up to {limit}: {len(lucky)}\n")
    
    # Find lucky twins (like prime twins)
    twins = [(n, n+2) for n in lucky if is_twin_lucky(lucky_set, n)]
    print(f"Lucky twins (like (3,5), (5,7), (11,13)):")
    print(twins[:10])
    print(f"Total lucky twins: {len(twins)}\n")
    
    # Statistics
    lucky_ratio = len(lucky) / limit
    print(f"Density of lucky numbers: {lucky_ratio:.1%}")
    print(f"Average gap between lucky numbers: {limit / len(lucky):.2f}\n")
    
    # Lucky numbers that are also prime
    def is_prime(n):
        if n < 2:
            return False
        for i in range(2, int(n**0.5) + 1):
            if n % i == 0:
                return False
        return True
    
    lucky_primes = [n for n in lucky if is_prime(n)]
    print(f"Lucky numbers that are also prime: {len(lucky_primes)}")
    print(lucky_primes[:15])
    print(f"\nFascinating fact: Some lucky and prime numbers coincide,")
    print(f"but they're generated by completely different processes!")
    
    # Visualization
    print("\n╔════════════════════════════════════════════╗")
    print("║  Lucky Numbers Scatter (every 5th shown)   ║")
    print("╚════════════════════════════════════════════╝")
    for i, n in enumerate(lucky):
        if i % 5 == 0:
            print("●", end="")
        else:
            print("·", end="")
        if (i + 1) % 50 == 0:
            print(f" ({lucky[i]})")
    print()

if __name__ == "__main__":
    analyze_lucky(1000)
